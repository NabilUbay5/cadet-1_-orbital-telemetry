/** Refresh the cockpit's bundled orbital reference; no runtime requests or API key. */
import { parseHorizonsVectors } from '../src/game/horizonsEphemeris.ts';

const url = new URL('https://ssd.jpl.nasa.gov/api/horizons.api');
url.searchParams.set('format', 'json');
const parameters = {
  COMMAND: '301', CENTER: '500@399', MAKE_EPHEM: 'YES', EPHEM_TYPE: 'VECTORS',
  START_TIME: '2027-01-16 07:00', STOP_TIME: '2027-01-17 07:00', STEP_SIZE: '10m',
  REF_SYSTEM: 'ICRF', REF_PLANE: 'FRAME', VEC_CORR: 'NONE', VEC_TABLE: '2',
  OUT_UNITS: 'KM-S', TIME_TYPE: 'TDB', CSV_FORMAT: 'YES', OBJ_DATA: 'NO',
};
for (const [key, value] of Object.entries(parameters)) url.searchParams.set(key, `'${value}'`);
const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
if (!response.ok) throw new Error(`Horizons HTTP ${response.status}`);
const body: unknown = await response.json();
if (!body || typeof body !== 'object' || !('result' in body) || typeof body.result !== 'string'
  || !('signature' in body) || !body.signature || typeof body.signature !== 'object'
  || !('version' in body.signature) || typeof body.signature.version !== 'string') {
  throw new Error('Invalid Horizons API response');
}
for (const required of ['Moon (301)', 'Earth (399)', 'ICRF', 'KM-S', 'TDB', 'GEOMETRIC cartesian states']) {
  if (!body.result.includes(required)) throw new Error(`Unexpected Horizons metadata: missing ${required}`);
}
const snapshot = {
  source: 'NASA/JPL Horizons', queryUrl: url.href, retrievedAt: new Date().toISOString(),
  apiVersion: body.signature.version, target: 'Moon (301)', center: 'Earth center (399)',
  frame: 'ICRF equatorial', timeScale: 'TDB', units: 'km, km/s',
  samples: parseHorizonsVectors(body.result),
};
const samples = snapshot.samples.map(row => `    [${row.join(', ')}]`).join(',\n');
const metadata = JSON.stringify({ ...snapshot, samples: undefined }, null, 2);
await Bun.write(new URL('../src/data/nasa/flightEphemeris.ts', import.meta.url),
  `// Generated by bun scripts/fetch-flight-ephemeris.ts. Do not edit by hand.\nimport type { EphemerisSnapshot } from '../../game/horizonsEphemeris.ts';\n\nexport const FLIGHT_EPHEMERIS: EphemerisSnapshot = ${metadata.slice(0, -2)},\n  samples: [\n${samples}\n  ],\n};\n`);
await Bun.write(new URL('../data/nasa/horizons-flight-raw.json', import.meta.url), `${JSON.stringify(body, null, 2)}\n`);
console.log(`Saved ${snapshot.samples.length} Horizons states and the original API response.`);
